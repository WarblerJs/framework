function selectPayloadType(table: TableMetadata, rowType: string, relations: readonly GeneratedRelation[]): string {
  const scalar = table.columns.map((column) => `  & (S extends { readonly ${column.fieldName}: true } ? { readonly ${column.fieldName}: ${rowType}["${column.fieldName}"] } : {})`);
  const relation = relations.map((item) => {
    const nested = `${item.target.modelName}RelationPayload<NonNullable<S["${item.field}"]>>`;
    return `  & (S extends { readonly ${item.field}: infer R } ? (R extends false | undefined ? {} : { readonly ${item.field}: ${item.kind === "many" ? `readonly ${nested}[]` : `${nested} | null`} }) : {})`;
  });
  return [`export type ${table.modelName}SelectPayload<S extends ${table.modelName}Select> =`, ...scalar, ...relation, ";"].join("\n");
}

function includePayloadType(table: TableMetadata, rowType: string, relations: readonly GeneratedRelation[]): string {
  const relation = relations.map((item) => {
    const nested = `${item.target.modelName}RelationPayload<NonNullable<I["${item.field}"]>>`;
    return `  & (I extends { readonly ${item.field}: infer R } ? (R extends false | undefined ? {} : { readonly ${item.field}: ${item.kind === "many" ? `readonly ${nested}[]` : `${nested} | null`} }) : {})`;
  });
  return [`export type ${table.modelName}IncludePayload<I extends ${table.modelName}Include> = ${rowType}`, ...relation, ";"].join("\n");
}

function runtimeModelSource(table: TableMetadata, allTables: readonly TableMetadata[]): string {
  const columns = table.columns.map((column) =>
    `{ field: ${JSON.stringify(column.fieldName)}, column: ${JSON.stringify(column.columnName)}, kind: ${JSON.stringify(runtimeKind(column))}, pgType: ${JSON.stringify(column.pgType)}, nullable: ${column.nullable}, unique: ${column.unique}, primaryKey: ${column.primaryKey}, aggregate: ${aggregateCapabilities(column)} }`
  );
  const relations = relationsFor(table, allTables).map((relation) =>
    `{ field: ${JSON.stringify(relation.field)}, kind: ${JSON.stringify(relation.kind)}, target: ${JSON.stringify(relation.target.modelName)}, localColumn: ${JSON.stringify(relation.localColumn)}, foreignColumn: ${JSON.stringify(relation.foreignColumn)} }`
  );
  return `${JSON.stringify(table.modelName)}: {
      name: ${JSON.stringify(table.modelName)},
      table: ${JSON.stringify(table.tableName)},
      defaultOrderColumn: ${JSON.stringify(table.primaryKey[0] ?? table.columns[0]?.columnName ?? "")},
      primaryKeyFields: Object.freeze([${table.primaryKey.map((columnName) => {
        const column = table.columns.find((candidate) => candidate.columnName === columnName);
        return JSON.stringify(column?.fieldName ?? columnName);
      }).join(", ")}]),
      columns: Object.freeze([${columns.join(", ")}]),
      relations: Object.freeze([${relations.join(", ")}]),
    }`;
}

function runtimeSchemaSource(allTables: readonly TableMetadata[]): string {
  return [
    "const READ_SCHEMA = Object.freeze({",
    "  models: Object.freeze({",
    ...allTables.map((table) => `    ${runtimeModelSource(table, allTables)},`),
    "  }),",
    "}) as RuntimeReadSchema;",
  ].join("\n");
}

