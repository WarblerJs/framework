import { DatabaseCompileError } from "../errors";
import type { ColumnMetadata, TableMetadata } from "../types/model.types";

const SERIAL_TYPES = new Set(["smallserial", "serial", "bigserial"]);
const NUMBER_TYPES = new Set(["smallint", "integer", "smallserial", "serial", "real", "double precision"]);
const STRING_NUMBER_TYPES = new Set(["bigint", "bigserial", "numeric", "money"]);
const DATE_TYPES = new Set(["date", "timestamp", "timestamptz"]);
const SUM_AVG_TYPES = new Set([...NUMBER_TYPES, ...STRING_NUMBER_TYPES]);
const FLOAT_TYPES = new Set(["real", "double precision"]);
const INTEGER_SUM_TYPES = new Set(["smallint", "integer", "smallserial", "serial"]);
const COMPARABLE_TYPES = new Set([
  ...SUM_AVG_TYPES,
  "char",
  "varchar",
  "text",
  "uuid",
  "date",
  "time",
  "timetz",
  "timestamp",
  "timestamptz",
  "interval",
  "enum",
  "inet",
  "cidr",
  "macaddr",
  "macaddr8",
  "bit",
  "varbit",
]);

function isAutoGenerated(column: ColumnMetadata): boolean {
  return column.identity || SERIAL_TYPES.has(column.pgType);
}

function isOptionalForInsert(column: ColumnMetadata): boolean {
  return column.nullable || column.default !== undefined || isAutoGenerated(column);
}

function baseTsType(column: ColumnMetadata): string {
  switch (column.pgType) {
    case "boolean":
      return "boolean";
    case "smallint":
    case "integer":
    case "smallserial":
    case "serial":
    case "real":
    case "double precision":
      return "number";
    case "bigint":
    case "bigserial":
    case "numeric":
    case "money":
      return "string";
    case "bytea":
      return "Uint8Array";
    case "json":
    case "jsonb":
      return "unknown";
    case "date":
    case "timestamp":
    case "timestamptz":
      return "Date";
    default:
      return "string";
  }
}

function tsType(column: ColumnMetadata): string {
  const base = baseTsType(column);
  const shape = column.sqlType.endsWith("[]") ? `readonly ${base}[]` : base;
  return column.nullable ? `${shape} | null` : shape;
}

function nonNullableTsType(column: ColumnMetadata): string {
  const base = baseTsType(column);
  return column.sqlType.endsWith("[]") ? `readonly ${base}[]` : base;
}

function pascalCase(name: string): string {
  return name.charAt(0).toUpperCase() + name.slice(1);
}

function lowerFirst(name: string): string {
  return name.charAt(0).toLowerCase() + name.slice(1);
}

function pluralize(name: string): string {
  if (/(?:s|x|z|ch|sh)$/iu.test(name)) return `${name}es`;
  if (/[^aeiou]y$/iu.test(name)) return `${name.slice(0, -1)}ies`;
  return `${name}s`;
}

function filterType(column: ColumnMetadata): string {
  const value = `${pascalCase(column.fieldName)}Value`;
  if (column.pgType === "boolean" || column.pgType === "bytea" || column.pgType === "json" || column.pgType === "jsonb") {
    return `${value} | EqualityFilter<${value}>`;
  }
  if (NUMBER_TYPES.has(column.pgType) || STRING_NUMBER_TYPES.has(column.pgType) || DATE_TYPES.has(column.pgType)) {
    return `${value} | ComparableFilter<${value}>`;
  }
  return `${value} | StringFilter<${value}>`;
}

function isArrayColumn(column: ColumnMetadata): boolean {
  return column.sqlType.endsWith("[]");
}

function supportsSumAvg(column: ColumnMetadata): boolean {
  return !isArrayColumn(column) && SUM_AVG_TYPES.has(column.pgType);
}

function supportsMinMax(column: ColumnMetadata): boolean {
  return !isArrayColumn(column) && COMPARABLE_TYPES.has(column.pgType);
}

function aggregateCapabilities(column: ColumnMetadata): string {
  return `Object.freeze({ count: true, sum: ${supportsSumAvg(column)}, avg: ${supportsSumAvg(column)}, min: ${supportsMinMax(column)}, max: ${supportsMinMax(column)} })`;
}

function sumTsType(column: ColumnMetadata): string {
  if (FLOAT_TYPES.has(column.pgType)) return "number | null";
  if (INTEGER_SUM_TYPES.has(column.pgType) || STRING_NUMBER_TYPES.has(column.pgType)) return "string | null";
  return `${nonNullableTsType(column)} | null`;
}

function avgTsType(column: ColumnMetadata): string {
  if (FLOAT_TYPES.has(column.pgType)) return "number | null";
  if (SUM_AVG_TYPES.has(column.pgType)) return "string | null";
  return `${nonNullableTsType(column)} | null`;
}

function aggregateResultTsType(column: ColumnMetadata, operation: "sum" | "avg" | "min" | "max"): string {
  if (operation === "sum") return sumTsType(column);
  if (operation === "avg") return avgTsType(column);
  return `${nonNullableTsType(column)} | null`;
}

function aggregateComparisonTsType(column: ColumnMetadata, operation: "sum" | "avg" | "min" | "max"): string {
  const result = aggregateResultTsType(column, operation);
  const scalar = nonNullableTsType(column);
  return result.includes(scalar) ? result : `${result} | ${scalar}`;
}

function runtimeKind(column: ColumnMetadata): "string" | "number" | "boolean" | "date" | "bytes" | "json" {
  if (column.pgType === "boolean") return "boolean";
  if (NUMBER_TYPES.has(column.pgType) || STRING_NUMBER_TYPES.has(column.pgType)) return "number";
  if (DATE_TYPES.has(column.pgType)) return "date";
  if (column.pgType === "bytea") return "bytes";
  if (column.pgType === "json" || column.pgType === "jsonb") return "json";
  return "string";
}

function relationFieldName(base: string, used: Set<string>): string {
  let candidate = base;
  let suffix = 2;
  while (used.has(candidate)) candidate = `${base}${suffix++}`;
  used.add(candidate);
  return candidate;
}

function relationBaseName(source: TableMetadata, target: TableMetadata, kind: "one" | "many"): string {
  if (kind === "one") return target.clientKey;
  if (source.modelName.startsWith(target.modelName) && source.modelName.length > target.modelName.length) {
    return pluralize(lowerFirst(source.modelName.slice(target.modelName.length)));
  }
  return pluralize(source.clientKey);
}

interface GeneratedRelation {
  readonly field: string;
  readonly kind: "one" | "many";
  readonly target: TableMetadata;
  readonly localColumn: string;
  readonly foreignColumn: string;
}

function relationsFor(table: TableMetadata, allTables: readonly TableMetadata[]): readonly GeneratedRelation[] {
  const relations: GeneratedRelation[] = [];
  const used = new Set(table.columns.map((column) => column.fieldName));
  for (const fk of table.foreignKeys) {
    const target = allTables.find((candidate) => candidate.tableName === fk.referencesTable);
    if (target === undefined) continue;
    relations.push(Object.freeze({
      field: relationFieldName(relationBaseName(table, target, "one"), used),
      kind: "one",
      target,
      localColumn: fk.column,
      foreignColumn: fk.referencesColumn,
    }));
  }
  for (const source of allTables) {
    for (const fk of source.foreignKeys) {
      if (fk.referencesTable !== table.tableName) continue;
      relations.push(Object.freeze({
        field: relationFieldName(relationBaseName(source, table, "many"), used),
        kind: "many",
        target: source,
        localColumn: fk.referencesColumn,
        foreignColumn: fk.column,
      }));
    }
  }
  return Object.freeze(relations);
}

function rowInterface(table: TableMetadata, typeName: string): string {
  return [`export interface ${typeName} {`, ...table.columns.map((column) => `  ${column.fieldName}: ${tsType(column)};`), "}"].join("\n");
}

function insertInterface(typeName: string, insertable: readonly ColumnMetadata[]): string {
  return [`export interface ${typeName} {`, ...insertable.map((column) => `  ${column.fieldName}${isOptionalForInsert(column) ? "?" : ""}: ${tsType(column)};`), "}"].join("\n");
}

function updateValueType(column: ColumnMetadata): string {
  const value = tsType(column);
  const set = `{ readonly set: ${value}; }`;
  if (NUMBER_TYPES.has(column.pgType) || STRING_NUMBER_TYPES.has(column.pgType)) {
    return `${value} | ${set} | { readonly increment: ${value}; } | { readonly decrement: ${value}; } | { readonly multiply: ${value}; } | { readonly divide: ${value}; }`;
  }
  return `${value} | ${set}`;
}

function updateInterface(typeName: string, updatable: readonly ColumnMetadata[]): string {
  return [`export interface ${typeName} {`, ...updatable.map((column) => `  ${column.fieldName}?: ${updateValueType(column)};`), "}"].join("\n");
}

function valueAliases(columns: readonly ColumnMetadata[]): string {
  return columns.map((column) => `type ${pascalCase(column.fieldName)}Value = ${tsType(column)};`).join("\n");
}

function whereInterface(table: TableMetadata, typeName: string, relations: readonly GeneratedRelation[]): string {
  const fields = table.columns.map((column) => `  readonly ${column.fieldName}?: ${filterType(column)};`);
  const relationFilters = relations.map((relation) => relation.kind === "many"
    ? `  readonly ${relation.field}?: { readonly some?: ${relation.target.modelName}Where; readonly none?: ${relation.target.modelName}Where; readonly every?: ${relation.target.modelName}Where; };`
    : `  readonly ${relation.field}?: { readonly is?: ${relation.target.modelName}Where; readonly isNot?: ${relation.target.modelName}Where; };`);
  return [
    `export interface ${typeName} {`,
    ...fields,
    ...relationFilters,
    `  readonly AND?: ${typeName} | readonly ${typeName}[];`,
    `  readonly OR?: readonly ${typeName}[];`,
    `  readonly NOT?: ${typeName} | readonly ${typeName}[];`,
    "}",
  ].join("\n");
}

function uniqueWhereType(typeName: string, uniqueColumns: readonly ColumnMetadata[]): string {
  return [`export type ${typeName} =`, ...uniqueColumns.map((column) => {
    const others = uniqueColumns.filter((other) => other.fieldName !== column.fieldName).map((other) => ` readonly ${other.fieldName}?: never;`).join("");
    return `  | ({ readonly ${column.fieldName}: ${tsType(column)};${others} })`;
  })].join("\n") + ";";
}

