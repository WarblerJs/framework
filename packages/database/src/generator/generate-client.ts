function relationImports(table: TableMetadata, relations: readonly GeneratedRelation[]): readonly string[] {
  const targets = [...new Set(relations.map((relation) => relation.target).filter((target) => target.modelName !== table.modelName))];
  return targets.map((target) => `import type { ${target.modelName}Include, ${target.modelName}IncludePayload, ${target.modelName}RelationArgs, ${target.modelName}RelationPayload, ${target.modelName}Select, ${target.modelName}SelectPayload, ${target.modelName}Where } from "./${target.clientKey}";`);
}

