function havingType(table: TableMetadata): string {
  const fields = table.columns.map((column) => {
    const operations: string[] = [`    readonly _count?: ${table.modelName}AggregateFilter<number>;`];
    if (supportsSumAvg(column)) {
      operations.push(`    readonly _sum?: ${table.modelName}AggregateFilter<${aggregateComparisonTsType(column, "sum")}>;`);
      operations.push(`    readonly _avg?: ${table.modelName}AggregateFilter<${aggregateComparisonTsType(column, "avg")}>;`);
    }
    if (supportsMinMax(column)) {
      operations.push(`    readonly _min?: ${table.modelName}AggregateFilter<${aggregateComparisonTsType(column, "min")}>;`);
      operations.push(`    readonly _max?: ${table.modelName}AggregateFilter<${aggregateComparisonTsType(column, "max")}>;`);
    }
    return [`  readonly ${column.fieldName}?: {`, ...operations, "  };"].join("\n");
  });
  return [`export interface ${table.modelName}GroupByHaving {`, ...fields, "}"].join("\n");
}

